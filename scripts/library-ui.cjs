const check = (name, ok, detail = '') => { results.push({ name, ok: !!ok, detail }); console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${!ok ? ` ${detail}` : ''}`) }
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const evaluate = (win, code) => win.webContents.executeJavaScript(`(async () => { ${code} })()`, true)
async function wait(win, code, timeout = 15000) { const end = Date.now() + timeout; while (Date.now() < end) { const value = await evaluate(win, code); if (value) return value; await sleep(100) } return null }
async function click(win, text) { return evaluate(win, `const b=Array.from(document.querySelectorAll('button')).find(b => b.textContent.trim() === ${JSON.stringify(text)}); if(!b || b.disabled) return false; b.click(); return true;`) }
async function fill(win, selector, value) { return evaluate(win, `const e=document.querySelector(${JSON.stringify(selector)}); if(!e) return false; const p=e.tagName==='TEXTAREA'?HTMLTextAreaElement.prototype:HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(p,'value').set.call(e,${JSON.stringify(String(value))}); e.dispatchEvent(new Event('input',{bubbles:true})); e.dispatchEvent(new Event('change',{bubbles:true})); return true;`) }
async function upload(win, name, bytes) { return evaluate(win, `const dt=new DataTransfer(); dt.items.add(new File([new Uint8Array(${JSON.stringify([...bytes])})],${JSON.stringify(name)})); const el=document.querySelector('.library-page input[type=file]'); el.files=dt.files; el.dispatchEvent(new Event('change',{bubbles:true})); return true;`) }
async function shot(win, name) { await sleep(250); writeFileSync(join(output, `${name}.png`), (await win.webContents.capturePage()).toPNG()) }
